import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
const out='evidencias';await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch();
const ctx=await browser.newContext({viewport:{width:1365,height:1000}});
const page=await ctx.newPage();
const url='https://patata-ni.github.io/eje-del-golfo-pwa-actividad/';
await page.goto(url);
await page.getByRole('heading',{name:'Cada recorrido cuenta.'}).waitFor();
await page.evaluate(async()=>{await navigator.serviceWorker.ready;if(!navigator.serviceWorker.controller)await new Promise(r=>navigator.serviceWorker.addEventListener('controllerchange',r,{once:true}));});
await page.screenshot({path:out+'/01-inicio-escritorio.png',fullPage:true});
await page.getByRole('link',{name:/Nueva incidencia/}).first().click();
await page.getByLabel('Titulo de la incidencia').count().catch(()=>0);
await page.locator('#title').fill('Revision de luces - evidencia academica');
await page.locator('#description').fill('Registro ficticio para comprobar persistencia local y consulta offline. No corresponde a una incidencia operativa real.');
await page.screenshot({path:out+'/02-formulario.png',fullPage:true});
await page.getByRole('button',{name:'Guardar incidencia',exact:true}).click();
await page.getByRole('heading',{name:'Revision de luces - evidencia academica',exact:true}).waitFor();
await ctx.setOffline(true);
await page.reload();
await page.getByRole('heading',{name:'Revision de luces - evidencia academica',exact:true}).waitFor();
await page.screenshot({path:out+'/03-offline-escritorio.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:out+'/04-offline-movil.png',fullPage:true});
const data=await page.evaluate(async()=>{
 const reg=await navigator.serviceWorker.ready;
 const db=await new Promise((resolve,reject)=>{const r=indexedDB.open('eje-golfo-pwa-actividad',1);r.onsuccess=()=>resolve(r.result);r.onerror=()=>reject(r.error);});
 const items=await new Promise((resolve,reject)=>{const r=db.transaction('incidencias').objectStore('incidencias').getAll();r.onsuccess=()=>resolve(r.result);r.onerror=()=>reject(r.error);});
 return {url:location.href,online:navigator.onLine,secureContext:isSecureContext,worker:{scriptURL:reg.active.scriptURL,state:reg.active.state,scope:reg.scope},caches:await caches.keys(),stores:Array.from(db.objectStoreNames),incidencias:items.map(({foto,...item})=>({...item,foto:foto?{type:foto.type,size:foto.size}:null})),viewport:{width:innerWidth,height:innerHeight},overflow:document.documentElement.scrollWidth>innerWidth,capturedAt:new Date().toISOString()};
});
await fs.writeFile(out+'/estado-offline.json',JSON.stringify(data,null,2));
await ctx.setOffline(false);
const manifest=await (await page.request.get(url+'manifest.json')).json();
await fs.writeFile(out+'/manifest-verificado.json',JSON.stringify(manifest,null,2));
await browser.close();
